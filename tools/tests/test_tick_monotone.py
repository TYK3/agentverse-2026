"""The runner logs global simulation time in t; equal-time events are valid."""

import json
import math
from itertools import pairwise
from pathlib import Path

import pytest

from tools import run_b2


def assert_monotone_time(rows):
    assert rows, 'empty log cannot demonstrate time ordering'
    previous = None
    for index, row in enumerate(rows):
        assert 't' in row, f'record {index} missing t'
        time = row['t']
        assert isinstance(time, (int, float)) and not isinstance(time, bool), f'record {index} invalid t type'
        assert math.isfinite(time), f'record {index} non-finite t'
        assert time >= 0, f'record {index} negative t'
        if previous is not None:
            assert time >= previous, f'record {index} time went backwards: {previous} -> {time}'
        previous = time


@pytest.mark.parametrize('floor', ['B1', 'B2', 'B3'])
def test_complete_real_log_time_never_decreases(floor):
    times = RECORDED[floor]['times']
    assert any(a == b for a, b in pairwise(times)), 'same-time events must remain covered'
    assert any(a < b for a, b in pairwise(times)), 'real clock advancement must remain covered'
    assert_monotone_time([{'t': time} for time in times])


@pytest.mark.parametrize('floor', ['B1', 'B2', 'B3'])
def test_short_real_writer_time_never_decreases(tmp_path, monkeypatch, floor):
    pytest.importorskip('mujoco')
    monkeypatch.setenv('GEMINI_MODE', 'off')
    _, path = run_b2.run(seed=0, max_t=2.2, out_dir=tmp_path, floor=floor)
    rows = [json.loads(line) for line in Path(path).read_text().splitlines()]
    assert sum(row['kind'] == 'pose' for row in rows) >= 3
    assert rows[-1]['t'] > rows[0]['t']
    assert_monotone_time(rows)


@pytest.mark.parametrize('mutation', [
    'backwards', 'missing', 'bool', 'string', 'nan', 'inf', 'negative', 'level_reset',
])
def test_bad_time_is_rejected(mutation):
    rows = [{'t': time} for time in RECORDED['B2']['times']]
    index = len(rows) // 2
    if mutation == 'backwards':
        rows[index]['t'] = rows[index - 1]['t'] - 0.1
        message = 'time went backwards'
    elif mutation == 'missing':
        del rows[index]['t']
        message = 'missing t'
    elif mutation in ('bool', 'string'):
        rows[index]['t'] = True if mutation == 'bool' else '1.0'
        message = 'invalid t type'
    elif mutation in ('nan', 'inf'):
        rows[index]['t'] = float(mutation)
        message = 'non-finite t'
    elif mutation == 'negative':
        rows[index]['t'] = -0.1
        message = 'negative t'
    else:
        # A genuine later level marker must not reset the global clock.
        index = RECORDED['B2']['level_indices'][-1]
        assert rows[index - 1]['t'] > 0
        rows[index]['t'] = 0.0
        message = 'time went backwards'
    with pytest.raises(AssertionError, match=message):
        assert_monotone_time(rows)


