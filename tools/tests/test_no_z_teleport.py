"""Height continuity uses pose elapsed time, not the 0.1-s internal tick cadence."""

import ast
import copy
import json
import math
from itertools import pairwise
from pathlib import Path

import pytest

from tools import run_b2

ROOT = Path(__file__).resolve().parents[2]
DT = 0.1
# _drive: <= MAX_RISE*SPEED*DT plus STEP_SLACK for each of three 1-cm substeps.
# 0.6*0.3*0.1 + ceil(0.3*0.1/0.01)*0.004 = 0.030 m per tick.
# Logged poses are ~1 Hz, not 10 Hz; two 3-decimal z values add <= 0.001 m error.
RISE_PER_TICK = 0.030
ROUNDING = 0.001


def project(rows):
    return {
        'poses': [[r['t'], r['pos'][2]] for r in rows if r['kind'] == 'pose'],
        'levels': [[r['t'], r['level']] for r in rows if r['kind'] == 'level'],
    }


def assert_continuous(poses):
    assert len(poses) >= 2, 'need two real pose samples, not a summary max_jump'
    assert all(math.isfinite(t) and math.isfinite(z) for t, z in poses), 'non-finite pose'
    for (ta, za), (tb, zb) in pairwise(poses):
        elapsed = tb - ta
        assert elapsed > 0, 'pose time must advance'
        ticks = math.ceil(elapsed / DT - 1e-8)
        bound = ticks * RISE_PER_TICK + ROUNDING
        assert abs(zb - za) <= bound + 1e-9, (
            f'z jump {abs(zb - za):.3f} m over {elapsed:.2f}s exceeds {bound:.3f} m'
        )
    # Level tags label continuous ramp motion in LevelWorld; they do not permit
    # an arbitrary z discontinuity. The same physical bound covers transitions.


@pytest.mark.parametrize(('file', 'name', 'expected'), [
    ('sim/world.py', 'SPEED', 0.3), ('sim/levels.py', 'MAX_RISE', 0.6),
    ('sim/levels.py', 'STEP_SLACK', 0.004), ('sim/levels.py', 'SUBSTEP', 0.01),
    ('sim/demo_descent.py', 'DT', 0.1),
])
def test_height_bound_matches_actual_driver_constants(file, name, expected):
    tree = ast.parse((ROOT / file).read_text())
    value = next(ast.literal_eval(node.value) for node in tree.body
                 if isinstance(node, ast.Assign)
                 and any(isinstance(target, ast.Name) and target.id == name for target in node.targets))
    assert value == expected, f'{name} changed: review the documented physical height bound'


@pytest.mark.parametrize('floor', ['B1', 'B2', 'B3'])
def test_short_real_pose_intervals(tmp_path, monkeypatch, floor):
    pytest.importorskip('mujoco')
    monkeypatch.setenv('GEMINI_MODE', 'off')
    _, path = run_b2.run(seed=0, max_t=2.2, out_dir=tmp_path, floor=floor)
    data = project([json.loads(line) for line in Path(path).read_text().splitlines()])
    assert len(data['poses']) >= 3
    assert_continuous(data['poses'])


@pytest.mark.parametrize('floor', ['B1', 'B2', 'B3'])
def test_all_recorded_pose_heights_through_real_level_transitions(floor):
    data = RECORDED[floor]
    assert data['levels'][0][1] == 'L1' and data['levels'][-1][1] == floor
    assert data['poses'][0][1] - data['poses'][-1][1] > 0.5, 'fixture must genuinely descend'
    assert_continuous(data['poses'])


@pytest.mark.parametrize('floor', ['B1', 'B2', 'B3'])
def test_injected_z_teleport_within_level_is_rejected(floor):
    poses = copy.deepcopy(RECORDED[floor]['poses'])
    poses[1][1] += 1
    with pytest.raises(AssertionError, match='z jump'):
        assert_continuous(poses)


@pytest.mark.parametrize('floor', ['B1', 'B2', 'B3'])
def test_level_record_does_not_hide_a_teleport(floor):
    data = RECORDED[floor]
    poses = copy.deepcopy(data['poses'])
    level_time = data['levels'][1][0]
    index = next(i for i in range(1, len(poses)) if poses[i - 1][0] < level_time <= poses[i][0])
    poses[index][1] += 1
    with pytest.raises(AssertionError, match='z jump'):
        assert_continuous(poses)


def test_worked_tick_bound_includes_only_coordinate_rounding():
    assert_continuous([[0, 0], [0.1, 0.031]])
    with pytest.raises(AssertionError, match='z jump'):
        assert_continuous([[0, 0], [0.1, 0.032]])


def test_zero_time_interval_is_not_a_height_exception():
    with pytest.raises(AssertionError, match='time must advance'):
        assert_continuous([[0, 0.675], [0, 0.7]])


